public class day5 {
    public static void main(String[] args) {
      // float (32-bit): pakai akhiran 'f', untuk angka desimal standar
        float tinggi = 155.5f;

      // double (64-bit): default Java, lebih akurat untuk angka desimal
        double ipk = 3.85;

      //menampilkan

        System.out.println("Tinggi niahh : " + tinggi + " cm");
        System.out.println("IPK niahh    : " + ipk);
    }
}
